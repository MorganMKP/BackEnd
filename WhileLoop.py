# While Loop Concept

# While loops are similar to for loops
# they have a condition and then a block of code below
#
# while (there is no heavy rain)
#     there will be electricity
#
# The code keeps running until the condition in the while statement becomes false
#
# The main difference between a while loop and a for loop is that,
# A FOR loop runs the code for a specified iteration but
# a WHILE loops keeps running the code for as long as the condition is True

# Eg 1
#
# counter = 5
# while counter > 0:
#     print (counter)
#     counter = counter - 1
# print ("The Loop Has Ended")

# Eg2

# counter = 8
# while counter % 2 == 0:
#     print (counter)
#     counter /= 2
# print ("The Loop Has Ended")

