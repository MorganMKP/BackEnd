# The use of "For Loop".
# Used to run a piece of code for a specified number of times

# They have 2 components (the number of times the code should run and the blck of code itself)
# Code is written as follows...
#             for i in range(_,_,_):
#                 < and the block of code >

# Note that 123 are placeholders...
# for i in range(1,2,3):

# 1 is starting point for i
# 2 is stopping point of i
# 3 is increment/step of i

# # EG
# for i in range(1,8,2)
# for the code above the loop will start from (1 to 3 to 5 to 7)
# Everytime a loop runs, it checks to see if it is higher than endpoint 8.
# If the condition remains true, the code will run till the next loop is greater than 8.
# at which the loop ends.

# for i in range(2,6,2)
# The code will run starting at 2, then 4.
# It will not run for 6 because the next loop, 6 is not lesser than then endpoint 6.